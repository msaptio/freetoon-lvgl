#define TR_FR_COUNT (sizeof TR_FR / sizeof TR_FR[0])
#define TR_FR_SLOTS 2048u            /* power of two, > 2x the table size */
typedef char tr_fr_slots_too_small[(TR_FR_COUNT * 2 < TR_FR_SLOTS) ? 1 : -1];

/* Open-addressing index on the English text: slot = entry index + 1. */
static uint16_t        tr_fr_slot[TR_FR_SLOTS];
static pthread_once_t  tr_fr_once = PTHREAD_ONCE_INIT;

static uint32_t tr_fr_hash(const char * s) {
    uint32_t h = 2166136261u;                    /* FNV-1a */
    while (*s) { h ^= (unsigned char)*s++; h *= 16777619u; }
    return h;
}

static void tr_fr_build(void) {
    for (size_t i = 0; i < TR_FR_COUNT; i++) {
        uint32_t k = tr_fr_hash(TR_FR[i].en) & (TR_FR_SLOTS - 1);
        while (tr_fr_slot[k]) k = (k + 1) & (TR_FR_SLOTS - 1);
        tr_fr_slot[k] = (uint16_t)(i + 1);
    }
}

const char * tr_fr(const char * nl, const char * en) {
    if (!en) return nl;
    pthread_once(&tr_fr_once, tr_fr_build);
    uint32_t k = tr_fr_hash(en) & (TR_FR_SLOTS - 1);
    for (uint16_t s; (s = tr_fr_slot[k]) != 0; k = (k + 1) & (TR_FR_SLOTS - 1)) {
        const tr_fr_entry_t * e = &TR_FR[s - 1];
        /* Same English can map to different Dutch (e.g. "Home" = Thuis /
           Startscherm), so the pair is the key. */
        if (strcmp(e->en, en) == 0 && (!nl || strcmp(e->nl, nl) == 0))
            return e->fr;
    }
    return en;
}
